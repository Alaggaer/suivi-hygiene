from conftest import connecter, photographier

def ouvrir_pms(page, nom="Karim", pin="1234"):
    connecter(page, nom, pin)
    page.click(".act:has-text('Espace PMS')")
    page.wait_for_selector("h1:has-text('Espace PMS')")

def test_equipier_refuse(page):
    ouvrir_pms(page, "Julie", "1111")
    assert "Réservé au chef et au responsable" in page.locator(".screen").inner_text()

def test_plan_action_prevoir_corriger_clore(page):
    ouvrir_pms(page)
    tuile = page.locator(".act:has-text(\"Plan d'action\")")
    tuile.wait_for()
    page.wait_for_selector(".act:has-text(\"Plan d'action\"):has-text('en retard')")
    assert "2 en cours · 1 en retard" in tuile.inner_text()
    tuile.click()
    moustiquaire = page.locator(".pa-carte:has-text('Moustiquaires')")
    assert "en retard" in moustiquaire.inner_text() and "Thomas" in moustiquaire.inner_text()
    joint = page.locator(".pa-carte:has-text('Joint de porte abîmé')")
    assert "Action pas encore prévue" in joint.inner_text()
    joint.locator("button:has-text(\"Prévoir l'action\")").click()
    valider = page.locator("#sheet button.bigbtn.ok")
    assert valider.inner_text() == "Décrivez l'action"
    page.fill("#sheet input[placeholder^='Ex. faire changer']", "Commander un joint neuf")
    page.fill("#sheet input[type=date]", "2099-01-15")
    page.select_option("#sheet select", label="Thomas")
    valider.click()
    page.wait_for_selector(".pa-carte:has-text('Joint de porte abîmé'):has-text('Commander un joint neuf')")
    assert "Thomas" in joint.inner_text() and "15 janv. 2099" in joint.inner_text()
    # Correction avec preuve, puis clôture par le chef (mineure)
    joint.locator("button:text-is('Corrigé')").click()
    page.fill("#sheet textarea", "Joint changé par le frigoriste")
    photographier(page)
    page.click("#sheet button:has-text('Corrigé')")
    page.wait_for_selector(".pa-carte:has-text('Joint de porte abîmé') .pill:has-text('Corrigée')")
    joint.locator("button:text-is('Clore')").click()
    page.wait_for_selector(".pa-carte:has-text('Joint de porte abîmé')", state="detached")
    # Majeure : corrigée par le chef, mais close par le siège seulement
    moustiquaire.locator("button:text-is('Corrigé')").click()
    page.fill("#sheet textarea", "Moustiquaire remplacée")
    page.click("#sheet button:has-text('Corrigé (sans photo)')")
    page.wait_for_selector(".pa-carte:has-text('Moustiquaires'):has-text('À valider par le siège')")
    assert moustiquaire.locator("button:text-is('Clore')").count() == 0

def test_controle_non_conforme_cree_une_action(page):
    ouvrir_pms(page)
    page.wait_for_selector(".act:has-text('Entretien technique') .badge")
    page.click(".act:has-text('Entretien technique')")
    cond = page.locator(".pa-carte:has-text('condenseurs')")
    assert "En retard" in cond.inner_text()
    hotte = page.locator(".pa-carte:has-text('Hotte et conduits')")
    assert "À jour" in hotte.inner_text() and "Hotte Service" not in hotte.inner_text()
    page.locator(".pa-carte:has-text('Joints des portes') button:has-text('Enregistrer un contrôle')").click()
    bouton = page.locator(".sm-form button.bigbtn")
    assert bouton.inner_text() == "Conforme ou non ?"
    page.click("button:text-is('Pas conforme')")
    assert bouton.inner_text() == "Décrivez le problème"
    page.fill("input[placeholder^='Ex. joint de la CF']", "Joint du frigo desserts décollé")
    assert bouton.inner_text() == "Prenez la photo"
    photographier(page)
    bouton.click()
    page.wait_for_selector("h1:has-text('Entretien technique')")
    assert "Non conforme" not in page.locator(".pa-carte:has-text('Joints des portes')").inner_text()
    page.click("text=← Espace PMS")
    page.click(".act:has-text(\"Plan d'action\")")
    page.wait_for_selector(".pa-carte:has-text('Joint du frigo desserts décollé')")
    # Contrôle par prestataire : photo du rapport obligatoire
    page.click("text=← Espace PMS")
    page.click(".act:has-text('Nuisibles')")
    page.locator(".pa-carte:has-text('Passage du prestataire') button:has-text('Enregistrer un contrôle')").click()
    page.fill("input[placeholder='Nom du prestataire']", "Rentokil")
    page.click("button:text-is('Conforme')")
    assert page.locator(".sm-form button.bigbtn").inner_text() == "Photographiez le rapport ou le certificat"
    photographier(page)
    page.click(".sm-form button.bigbtn")
    page.wait_for_selector(".pa-carte:has-text('Passage du prestataire') .pill:has-text('À jour')")

def test_sondes_verification_et_ajout(page):
    ouvrir_pms(page)
    page.click(".act:has-text('Sondes')")
    ir = page.locator(".pa-carte:has-text('infrarouge')")
    assert "Jamais fait" in ir.inner_text()
    ir.locator("button:text-is('Vérifier')").click()
    page.fill("input[inputmode=decimal]", "1,2")
    page.wait_for_selector(".pill.bad:has-text('Hors tolérance')")
    page.fill("input[inputmode=decimal]", "0,3")
    page.wait_for_selector(".pill.ok:has-text('Dans la tolérance')")
    page.fill("input[inputmode=decimal]", "1,2")
    photographier(page)
    page.click(".sm-form button.bigbtn")
    page.wait_for_selector(".pa-carte.hs:has-text('infrarouge'):has-text('Hors service')")
    page.click("text=+ Ajouter un appareil")
    page.fill("input[placeholder^='Ex. Sonde piquante']", "Sonde réserve")
    page.click(".sm-form button:has-text('Ajouter')")
    page.wait_for_selector(".pa-carte:has-text('Sonde réserve'):has-text('Jamais fait')")

def test_siege_vue_groupe_fiche_et_modeles(page):
    page.goto("http://localhost:4173/#siege")
    page.wait_for_selector(".s3-carte")
    page.click("button.s3-retour:text-is('PMS')")
    page.wait_for_selector(".pms-groupe")
    dallas = page.locator(".pms-groupe tr:has-text('DALLAS')")
    assert "1 en retard" in dallas.inner_text()
    dallas.click()
    page.wait_for_selector("h2.pms-nom:has-text('DALLAS')")
    ligne = page.locator("tr:has-text('Moustiquaires : moustiquaire')")
    ligne.locator("button:text-is('modifier')").click()
    page.fill("input[aria-label='Action prévue']", "Poser une moustiquaire neuve")
    page.fill("input[aria-label='Échéance']", "2099-02-01")
    ligne.locator("button:text-is('Enregistrer')").click()
    page.wait_for_selector("tr:has-text('Poser une moustiquaire neuve')")
    presta = page.locator("tr:has-text('Passage du prestataire')")
    presta.locator("text=Déposer un rapport").click()
    enr = page.locator("[aria-label=Rapport] button.s3-verifier")
    page.click("[aria-label=Rapport] button:text-is('Conforme')")
    assert enr.inner_text() == "Joignez le rapport (PDF)"
    page.set_input_files("input[aria-label='Rapport PDF']", files=[{"name": "r.pdf", "mimeType": "application/pdf", "buffer": b"%PDF-1.4"}])
    enr.click()
    page.wait_for_selector(".pill.ok:has-text('Contrôle enregistré')")
    page.wait_for_selector("tr:has-text('Passage du prestataire'):has-text('À jour')")
    page.click("text=← PMS de tous les restaurants")
    page.click("button[role=tab]:has-text('Contrôles à faire')")
    page.click("text=+ Ajouter un contrôle")
    page.fill("[aria-label=Contrôle] input[placeholder^='Ex. Nettoyage']", "Contrôle des extincteurs")
    page.click("[aria-label=Contrôle] .g-jour:has-text('chaque année')")
    page.click("[aria-label=Contrôle] button:has-text('Rapport ou certificat')")
    page.click("[aria-label=Contrôle] button.s3-verifier")
    page.wait_for_selector("tr:has-text('Contrôle des extincteurs'):has-text('chaque année')")
